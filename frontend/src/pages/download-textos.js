/** Idioma de la página: ?lang=, la última elección, el del navegador o castellano. */
export function elegirIdioma({ parametro, guardado, navegador = [] } = {}) {
    for (const candidato of [parametro, guardado, ...navegador]) {
        const base = String(candidato ?? '').toLowerCase().split('-')[0];
        if (IDIOMAS.includes(base)) return base;
    }
    return 'es';
}

/** Tamaño legible de la APK («10,5 MB») en el idioma de la página. */
export function tamanoLegible(bytes, idioma = 'es') {
    const n = Number(bytes);
    if (!Number.isFinite(n) || n <= 0) return '';
    return `${new Intl.NumberFormat(idioma, { maximumFractionDigits: 1 }).format(n / (1024 * 1024))} MB`;
}
